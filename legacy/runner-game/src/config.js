// كل الأرقام اللي تتحكم بإحساس اللعبة في مكان واحد.
// جرّب تغيّرها وشوف الفرق!

export const CONFIG = {
  // ---- الطريق ----
  laneWidth: 2.2, // عرض الحارة الوحدة (بالمتر)
  laneCount: 3, // عدد الحارات

  // ---- السرعة ----
  startSpeed: 12, // سرعة البداية (متر/ثانية)
  maxSpeed: 38, // أقصى سرعة (توصلها بعد 3 دقايق تقريباً)
  speedIncrease: 0.25, // كم تزيد السرعة كل ثانية بالبداية (الزيادة تخف شوي شوي كل ما قربت من الأقصى)

  // ---- الصعوبة ----
  levelDistance: 400, // كل كم متر يطلع "المستوى الجديد"

  // ---- الشخصية ----
  laneChangeSpeed: 14, // سرعة الانتقال بين الحارات (أكبر = أسرع)
  gravity: 45, // الجاذبية
  jumpVelocity: 15, // قوة القفزة (ارتفاع القفزة تقريباً 2.5 متر)
  slideDuration: 0.75, // مدة الانزلاق بالثواني

  // ---- الأداء ----
  maxPixelRatio: 2, // حد أقصى لدقة الشاشة (الجوالات الحديثة دقتها 3 وهذا يثقل)
  shadowMapSize: 1024, // دقة الظلال
};

// موقع كل حارة على محور X: الحارة 0 يسار، 1 وسط، 2 يمين
export function laneToX(lane) {
  return (lane - 1) * CONFIG.laneWidth;
}
